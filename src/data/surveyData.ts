export function computeSurveyStats(records: SurveyRecord[]) {
  const total = records.length;
  if (total === 0) return null;

  // Problem counts
  const problemsCount: Record<string, number> = {};
  records.forEach(r => {
    r.majorProblems.forEach(p => {
      const clean = p.trim();
      if (clean) problemsCount[clean] = (problemsCount[clean] || 0) + 1;
    });
  });

  const problemsData = Object.entries(problemsCount)
    .sort((a, b) => b[1] - a[1])
    .map(([name, count]) => ({
      name,
      count,
      percent: Math.round((count / total) * 100)
    }));

  // Desired amenities counts
  const amenitiesCount: Record<string, number> = {};
  records.forEach(r => {
    r.desiredAmenities.forEach(a => {
      const clean = a.trim();
      if (clean) amenitiesCount[clean] = (amenitiesCount[clean] || 0) + 1;
    });
  });

  const amenitiesData = Object.entries(amenitiesCount)
    .sort((a, b) => b[1] - a[1])
    .map(([name, count]) => ({
      name,
      count,
      percent: Math.round((count / total) * 100)
    }));

  // Preferred times
  const timeCounts: Record<string, number> = {};
  records.forEach(r => {
    const t = r.preferredTime || 'Unspecified';
    timeCounts[t] = (timeCounts[t] || 0) + 1;
  });
  const timeData = Object.entries(timeCounts).map(([name, value]) => ({
    name,
    value,
    percent: Math.round((value / total) * 100)
  }));

  // Avoided due to evening closure
  const avoidedCounts: Record<string, number> = {};
  records.forEach(r => {
    const v = r.avoidedDueToEveningClosure || 'Unknown';
    avoidedCounts[v] = (avoidedCounts[v] || 0) + 1;
  });
  const avoidedData = Object.entries(avoidedCounts).map(([name, value]) => ({
    name,
    value,
    percent: Math.round((value / total) * 100)
  }));

  // Better lighting impact
  const lightingCounts: Record<string, number> = {};
  records.forEach(r => {
    const v = r.lightingEncouragesPlay || 'Unspecified';
    lightingCounts[v] = (lightingCounts[v] || 0) + 1;
  });

  // Ideal closing time
  const closingCounts: Record<string, number> = {};
  records.forEach(r => {
    const v = r.idealClosingTime || 'Unspecified';
    closingCounts[v] = (closingCounts[v] || 0) + 1;
  });
  const closingData = Object.entries(closingCounts)
    .sort((a, b) => b[1] - a[1])
    .map(([name, value]) => ({
      name,
      value,
      percent: Math.round((value / total) * 100)
    }));

  // Would use night court
  const wouldUseCounts: Record<string, number> = {};
  records.forEach(r => {
    const v = r.wouldUseNightCourt || 'Unspecified';
    wouldUseCounts[v] = (wouldUseCounts[v] || 0) + 1;
  });
  const wouldUseData = Object.entries(wouldUseCounts).map(([name, value]) => ({
    name,
    value,
    percent: Math.round((value / total) * 100)
  }));

  // Recommend project
  const recommendCounts: Record<string, number> = {};
  records.forEach(r => {
    const v = r.recommendProject || 'Unspecified';
    recommendCounts[v] = (recommendCounts[v] || 0) + 1;
  });

  // Calculate key headline metrics
  const eveningOrNightPlay = records.filter(r => 
    r.preferredTime.includes('Evening') || r.preferredTime.includes('Night')
  ).length;

  const avoidedYesCount = (avoidedCounts['Yes'] || 0);
  const lightingYesCount = (lightingCounts['Yes'] || 0);
  const wouldUseDefOrProb = (wouldUseCounts['Definitely'] || 0) + (wouldUseCounts['Probably'] || 0);

  return {
    totalResponses: total,
    problemsData,
    amenitiesData,
    timeData,
    avoidedData,
    closingData,
    wouldUseData,
    headline: {
      avoidedEveningPercent: Math.round((avoidedYesCount / total) * 100),
      lightingEncouragesPercent: Math.round((lightingYesCount / total) * 100),
      wouldUseNightCourtPercent: Math.round((wouldUseDefOrProb / total) * 100),
      preferEveningNightPercent: Math.round((eveningOrNightPlay / total) * 100),
      dailyOrFrequentPercent: Math.round((records.filter(r => r.frequency === 'Daily' || r.frequency === '3–4 times a week').length / total) * 100)
    },
    qualitativeFeedback: records.filter(r => r.additionalComments || r.suggestedImprovements).map(r => ({
      timestamp: r.timestamp,
      occupation: r.occupation,
      ageGroup: r.ageGroup,
      improvement: r.suggestedImprovements,
      comment: r.additionalComments
    }))
  };
}
